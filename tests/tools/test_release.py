def write_tree(root, *, crate_two=CRATE_TWO, root_cargo=ROOT_CARGO):
    files = {
        "src-tauri/tauri.conf.json": TAURI_CONF,
        "frontend/package.json": PACKAGE_JSON,
        "frontend/package-lock.json": PACKAGE_LOCK,
        "Cargo.toml": root_cargo,
        "crates/one/Cargo.toml": CRATE_ONE,
        "crates/two/Cargo.toml": crate_two,
        "Cargo.lock": CARGO_LOCK,
    }
    for name, text in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="")


def snapshot(root):
    return {path: path.read_bytes() for path in sorted(root.rglob("*")) if path.is_file()}


def changed_lines(before, after):
    old = before.decode("utf-8").splitlines()
    new = after.decode("utf-8").splitlines()
    assert len(old) == len(new), "line count changed"
    return [(a, b) for a, b in zip(old, new) if a != b]


def run_main(argv, root):
    stdout, stderr = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
        code = release.main(argv, root=root)
    return code, stdout.getvalue(), stderr.getvalue()


class TempTree(unittest.TestCase):
    def setUp(self):
        LOCAL_ROOT.mkdir(exist_ok=True)
        self.temp = tempfile.TemporaryDirectory(dir=LOCAL_ROOT)
        self.root = Path(self.temp.name)

    def tearDown(self):
        self.temp.cleanup()


class VersionParsingTests(unittest.TestCase):
    def test_release_and_numbered_prerelease_map_to_msi_versions(self):
        # GIVEN valid versions WHEN parsed THEN the MSI version carries the trailing number.
        self.assertEqual(release.parse_version("1.2.3"), ("1.2.3", "1.2.3"))
        self.assertEqual(release.parse_version("0.1.0-alpha.1"), ("0.1.0-alpha.1", "0.1.0.1"))
        self.assertEqual(release.parse_version("0.1.0-7"), ("0.1.0-7", "0.1.0.7"))
        self.assertEqual(release.parse_tag("v0.1.0-rc.2"), ("0.1.0-rc.2", "0.1.0.2"))

    def test_invalid_versions_are_refused(self):
        # GIVEN versions that SemVer, Cargo, npm or Windows Installer cannot all carry
        # WHEN parsed THEN each one is refused.
        for text in ("1.2", "01.2.3", "1.2.3+build.1", "1.2.3-", "1.2.3-alpha", "1.2.3-alpha.01",
                     "256.0.0", "0.256.0", "0.0.65536", "0.1.0-alpha.65536", " 1.2.3", "1.2.3\n"):
            with self.subTest(text=text), self.assertRaises(release.ReleaseError):
                release.parse_version(text)

    def test_tag_must_start_with_v(self):
        with self.assertRaises(release.ReleaseError):
            release.parse_tag("0.1.0")


class SetVersionTests(TempTree):
    def test_version_changes_only_first_party_version_strings(self):
        # GIVEN a tree at mixed first-party versions
        write_tree(self.root)
        before = snapshot(self.root)
        # WHEN the release version is set
        code, _, _ = run_main_without_cargo(["version", "0.1.0-alpha.1"], self.root)
        # THEN only the version lines change, and every manifest agrees with the tag.
        self.assertEqual(code, 0)
        self.assertEqual(release.check(self.root, "v0.1.0-alpha.1"), [])
        after = snapshot(self.root)
        changes = {path.relative_to(self.root).as_posix(): changed_lines(before[path], after[path]) for path in before}
        self.assertEqual(changes["src-tauri/tauri.conf.json"], [
            ('  "version": "0.0.0",', '  "version": "0.1.0-alpha.1",'),
            ('        "version": "0.0.0",', '        "version": "0.1.0.1",'),
        ])
        self.assertEqual(len(changes["frontend/package.json"]), 1)
        self.assertEqual(changes["frontend/package-lock.json"], [
            ('  "version": "0.0.0",', '  "version": "0.1.0-alpha.1",'),
            ('      "version": "0.0.0",', '      "version": "0.1.0-alpha.1",'),
        ])
        self.assertEqual(changes["crates/two/Cargo.toml"], [
            ('version = "0.1.0" # trailing comment stays', 'version = "0.1.0-alpha.1" # trailing comment stays'),
        ])
        self.assertEqual(changes["Cargo.toml"], [])
        lock = tomllib.loads(after[self.root / "Cargo.lock"].decode("utf-8"))
        versions = {p["name"]: p["version"] for p in lock["package"]}
        self.assertEqual(versions, {"persephone-one": "0.1.0-alpha.1", "persephone-two": "0.1.0-alpha.1", "serde": "0.0.0"})
        npm = json.loads(after[self.root / "frontend/package-lock.json"])
        self.assertEqual(npm["packages"]["node_modules/same-version"]["version"], "0.0.0")
        # The [features] key named `version` is not a package version.
        two = tomllib.loads(after[self.root / "crates/two/Cargo.toml"].decode("utf-8"))
        self.assertEqual(two["features"], {"version": []})

    def test_setting_the_same_version_twice_is_idempotent(self):
        write_tree(self.root)
        release.set_version(self.root, "1.0.0")
        once = snapshot(self.root)
        release.set_version(self.root, "1.0.0")
        self.assertEqual(snapshot(self.root), once)
        tauri = json.loads((self.root / "src-tauri/tauri.conf.json").read_text(encoding="utf-8"))
        self.assertEqual(tauri["bundle"]["windows"]["wix"]["version"], "1.0.0")

    def test_inherited_crate_version_sets_the_workspace_version(self):
        # GIVEN a member that inherits its version from [workspace.package]
        inherited = CRATE_TWO.replace('version = "0.1.0" # trailing comment stays', "version.workspace = true")
        workspace = ROOT_CARGO + 'version = "0.1.0"\n'
        write_tree(self.root, crate_two=inherited, root_cargo=workspace)
        # WHEN the version is set THEN the workspace version holds it and the tag check passes.
        release.set_version(self.root, "2.0.0")
        root = tomllib.loads((self.root / "Cargo.toml").read_text(encoding="utf-8"))
        self.assertEqual(root["workspace"]["package"]["version"], "2.0.0")
        self.assertEqual(release.check(self.root, "v2.0.0"), [])

    def test_invalid_version_leaves_every_file_unchanged(self):
        # GIVEN a tree WHEN an unusable version is requested THEN nothing is written and the exit code is 2.
        write_tree(self.root)
        before = snapshot(self.root)
        code, _, stderr = run_main(["version", "0.1.0-alpha"], self.root)
        self.assertEqual(code, 2)
        self.assertIn("must end in a number", stderr)
        self.assertEqual(snapshot(self.root), before)

    def test_missing_msi_version_is_refused_before_any_write(self):
        # GIVEN a Tauri config without bundle.windows.wix.version
        write_tree(self.root)
        conf = self.root / "src-tauri/tauri.conf.json"
        conf.write_text(TAURI_CONF.replace('        "version": "0.0.0",\n', ""), encoding="utf-8", newline="")
        before = snapshot(self.root)
        # WHEN the version is set THEN it fails and no file changes.
        with self.assertRaises(release.ReleaseError):
            release.set_version(self.root, "0.1.0")
        self.assertEqual(snapshot(self.root), before)


class CheckTagTests(TempTree):
    def test_matching_tag_passes(self):
        write_tree(self.root)
        release.set_version(self.root, "0.3.0")
        code, stdout, _ = run_main(["check-tag", "v0.3.0"], self.root)
        self.assertEqual((code, stdout.strip()), (0, "All versions match v0.3.0."))

    def test_each_differing_manifest_is_listed(self):
        # GIVEN an untouched tree with crates at 0.0.0 and 0.1.0
        write_tree(self.root)
        # WHEN checked against v0.1.0
        code, _, stderr = run_main(["check-tag", "v0.1.0"], self.root)
        # THEN it fails and names every place still at 0.0.0, but not those at 0.1.0.
        self.assertEqual(code, 1)
        self.assertIn("src-tauri/tauri.conf.json version: '0.0.0'", stderr)
        self.assertIn("frontend/package-lock.json packages[\"\"].version", stderr)
        self.assertIn("crates/one/Cargo.toml (persephone-one)", stderr)
        self.assertIn("Cargo.lock persephone-one", stderr)
        self.assertNotIn("crates/two/Cargo.toml", stderr)
        self.assertNotIn("Cargo.lock persephone-two", stderr)
        self.assertIn("7 version(s) differ from v0.1.0", stderr)

    def test_stale_msi_version_fails_the_check(self):
        # GIVEN a tree where only the MSI version was not updated
        write_tree(self.root)
        release.set_version(self.root, "0.2.0-beta.3")
        conf = self.root / "src-tauri/tauri.conf.json"
        conf.write_text(conf.read_text(encoding="utf-8").replace('"0.2.0.3"', '"0.2.0.2"'), encoding="utf-8", newline="")
        # WHEN checked THEN the MSI version is the only mismatch.
        mismatches = release.check(self.root, "v0.2.0-beta.3")
        self.assertEqual([(place, wanted) for place, _, wanted in mismatches],
                         [("src-tauri/tauri.conf.json bundle.windows.wix.version (MSI)", "0.2.0.3")])

    def test_malformed_tag_exits_2(self):
        write_tree(self.root)
        self.assertEqual(run_main(["check-tag", "release-1"], self.root)[0], 2)


class RepositoryTests(TempTree):
    def test_repository_manifests_are_readable_and_editable(self):
        # GIVEN copies of the repository's own manifests
        for relative in ("src-tauri/tauri.conf.json", "frontend/package.json", "frontend/package-lock.json", "Cargo.toml", "Cargo.lock"):
            target = self.root / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(release.ROOT / relative, target)
        for manifest in release._crate_manifests(release.ROOT):
            target = self.root / manifest.relative_to(release.ROOT)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(manifest, target)
        # WHEN every version is read and then set on the copy
        self.assertTrue(all(isinstance(version, str) for _, version in release.current_versions(self.root)))
        release.set_version(self.root, "9.8.7-rc.6")
        # THEN the copy matches the tag and the real tree is untouched.
        self.assertEqual(release.check(self.root, "v9.8.7-rc.6"), [])
        self.assertNotIn("9.8.7", (release.ROOT / "Cargo.lock").read_text(encoding="utf-8"))


class BundleConfigTests(TempTree):
    def test_release_config_names_sidecars_and_licence_files(self):
        # GIVEN generated notices WHEN the release configuration is written
        notices = self.root / "notices.txt"
        notices.write_text("notices\n", encoding="utf-8")
        output = self.root / "out/tauri.release.json"
        code, _, _ = run_main(["bundle-config", "--notices", str(notices), "--output", str(output)], release.ROOT)
        # THEN it adds both sidecars and both licence files, and no signing hook.
        self.assertEqual(code, 0)
        bundle = json.loads(output.read_text(encoding="utf-8"))["bundle"]
        self.assertIs(bundle["active"], True)
        self.assertEqual(bundle["externalBin"], ["binaries/persephone", "binaries/persephone-media-worker"])
        resources = {(release.ROOT / "src-tauri" / source).resolve(): target for source, target in bundle["resources"].items()}
        self.assertEqual(resources, {(release.ROOT / "LICENSE").resolve(): "LICENSE.txt",
                                     notices.resolve(): "THIRD-PARTY-NOTICES.txt"})
        self.assertNotIn("windows", bundle)

    def test_missing_notices_are_refused(self):
        output = self.root / "tauri.release.json"
        code, _, stderr = run_main(["bundle-config", "--notices", str(self.root / "absent.txt"), "--output", str(output)], release.ROOT)
        self.assertEqual(code, 2)
        self.assertIn("notices not found", stderr)
        self.assertFalse(output.exists())


@unittest.skipUnless(shutil.which("cargo"), "cargo is required")
class CargoLockTests(TempTree):
    def make_workspace(self):
        (self.root / "Cargo.toml").write_text(ROOT_CARGO, encoding="utf-8")
        for name, manifest in (("one", CRATE_ONE.replace('serde = { version = "=1.0.0" }\n', "")), ("two", CRATE_TWO)):
            crate = self.root / "crates" / name
            (crate / "src").mkdir(parents=True)
            (crate / "Cargo.toml").write_text(manifest, encoding="utf-8")
            (crate / "src/lib.rs").write_text("", encoding="utf-8")
        for name, text in (("src-tauri/tauri.conf.json", TAURI_CONF), ("frontend/package.json", PACKAGE_JSON),
                           ("frontend/package-lock.json", PACKAGE_LOCK)):
            (self.root / name).parent.mkdir(parents=True, exist_ok=True)
            (self.root / name).write_text(text, encoding="utf-8")
        subprocess.run(["cargo", "generate-lockfile", "--offline"], cwd=self.root, check=True, capture_output=True)

    def test_edited_lock_is_accepted_by_cargo_locked(self):
        # GIVEN a real Cargo workspace and its generated lockfile
        self.make_workspace()
        self.assertTrue(release.cargo_lock_is_valid(self.root))
        # WHEN the version is set THEN `cargo metadata --locked` still accepts the lockfile.
        code, _, _ = run_main(["version", "0.4.0-alpha.2"], self.root)
        self.assertEqual(code, 0)
        self.assertTrue(release.cargo_lock_is_valid(self.root))

    def test_lock_left_at_the_old_version_is_rejected(self):
        # GIVEN manifests at a new version but a lockfile left at the old one (negative control)
        self.make_workspace()
        lock = (self.root / "Cargo.lock").read_text(encoding="utf-8")
        release.set_version(self.root, "0.5.0")
        (self.root / "Cargo.lock").write_text(lock, encoding="utf-8")
        # WHEN Cargo checks the lockfile THEN it refuses it, and `version` would report failure.
        with contextlib.redirect_stderr(io.StringIO()):
            self.assertFalse(release.cargo_lock_is_valid(self.root))


def run_main_without_cargo(argv, root):
    """Run `main` with the Cargo check replaced; CargoLockTests cover the real one."""
    with patch.object(release, "cargo_lock_is_valid", return_value=True):
        return run_main(argv, root)


